  function animateSparkles() {
    if (!sparkleCtx) return;
    sparkleCtx.clearRect(0, 0, sparkleCanvas.width, sparkleCanvas.height);

    if (Math.random() < 0.15) {
      sparkles.push({
        x: Math.random() * sparkleCanvas.width,
        y: Math.random() * sparkleCanvas.height,
        size: Math.random() * 2.5 + 0.5,
        opacity: 1,
        decay: Math.random() * 0.015 + 0.005,
      });
    }

    if (sparkles.length > 60) sparkles.shift();

    for (let i = sparkles.length - 1; i >= 0; i--) {
      const s = sparkles[i];
      sparkleCtx.save();
      sparkleCtx.globalAlpha = s.opacity;
      sparkleCtx.fillStyle = '#FFD6E0';
      sparkleCtx.shadowBlur = 8;
      sparkleCtx.shadowColor = 'rgba(255, 143, 171, 0.6)';
      sparkleCtx.beginPath();
      sparkleCtx.moveTo(s.x, s.y - s.size);
      sparkleCtx.lineTo(s.x + s.size * 0.4, s.y);
      sparkleCtx.lineTo(s.x, s.y + s.size);
      sparkleCtx.lineTo(s.x - s.size * 0.4, s.y);
      sparkleCtx.closePath();
      sparkleCtx.fill();
      sparkleCtx.restore();
      s.opacity -= s.decay;
      if (s.opacity <= 0) sparkles.splice(i, 1);
    }
    requestAnimationFrame(animateSparkles);
  }

