  function createCarousel({ trackId, dotsId, prevId, nextId, counterId, autoPlayDelay = 4000 }) {
    const track = document.getElementById(trackId);
    const dotsContainer = dotsId ? document.getElementById(dotsId) : null;
    const prevBtn = document.getElementById(prevId);
    const nextBtn = document.getElementById(nextId);
    const counterEl = counterId ? document.getElementById(counterId) : null;
    if (!track) return null;

    const slides = track.querySelectorAll('.carousel-slide');
    const totalSlides = slides.length;
    if (totalSlides === 0) return null;

    let currentSlide = 0;
    let startX = 0;
    let currentX = 0;
    let isDragging = false;
    let autoPlayTimer = null;

    // Build dots only if <= 15 slides so mobile UI stays clean
    if (dotsContainer) {
      dotsContainer.innerHTML = '';
      if (totalSlides <= 15) {
        slides.forEach((_, i) => {
          const dot = document.createElement('button');
          dot.classList.add('carousel-dot');
          if (i === 0) dot.classList.add('active');
          dot.setAttribute('aria-label', `Slide ${i + 1}`);
          dot.addEventListener('click', () => { goToSlide(i); resetAutoPlay(); });
          dotsContainer.appendChild(dot);
        });
      } else {
        dotsContainer.style.display = 'none';
      }
    }

    function updateCounter() {
      if (counterEl) {
        counterEl.textContent = `${currentSlide + 1} / ${totalSlides}`;
      }
    }
    updateCounter();

    function goToSlide(index) {
      currentSlide = Math.max(0, Math.min(index, totalSlides - 1));
      track.style.transform = `translateX(-${currentSlide * 100}%)`;
      updateDots();
      updateCounter();
    }

    function updateDots() {
      if (!dotsContainer || totalSlides > 15) return;
      dotsContainer.querySelectorAll('.carousel-dot').forEach((dot, i) => {
        dot.classList.toggle('active', i === currentSlide);
      });
    }

    function nextSlide() {
      goToSlide(currentSlide >= totalSlides - 1 ? 0 : currentSlide + 1);
    }

    function prevSlide() {
      goToSlide(currentSlide <= 0 ? totalSlides - 1 : currentSlide - 1);
    }

    if (prevBtn) prevBtn.addEventListener('click', () => { prevSlide(); resetAutoPlay(); });
    if (nextBtn) nextBtn.addEventListener('click', () => { nextSlide(); resetAutoPlay(); });

    // Touch swipe
    track.addEventListener('touchstart', (e) => {
      isDragging = true; startX = e.touches[0].clientX;
    }, { passive: true });
    track.addEventListener('touchmove', (e) => {
      if (!isDragging) return; currentX = e.touches[0].clientX;
    }, { passive: true });
    track.addEventListener('touchend', () => {
      if (!isDragging) return; isDragging = false;
      const diff = startX - currentX;
      if (Math.abs(diff) > 40) {
        diff > 0 ? nextSlide() : prevSlide();
        resetAutoPlay();
      }
    });

    // Mouse drag
    track.addEventListener('mousedown', (e) => {
      isDragging = true; startX = e.clientX; e.preventDefault();
    });
    document.addEventListener('mousemove', (e) => {
      if (!isDragging) return; currentX = e.clientX;
    });
    document.addEventListener('mouseup', () => {
      if (!isDragging) return; isDragging = false;
      const diff = startX - currentX;
      if (Math.abs(diff) > 40) {
        diff > 0 ? nextSlide() : prevSlide();
        resetAutoPlay();
      }
    });

    function startAutoPlay() {
      if (autoPlayDelay > 0) {
        autoPlayTimer = setInterval(nextSlide, autoPlayDelay);
      }
    }
    function resetAutoPlay() {
      if (autoPlayTimer) clearInterval(autoPlayTimer);
      startAutoPlay();
    }
    startAutoPlay();

    return { goToSlide, nextSlide, prevSlide };
  }

